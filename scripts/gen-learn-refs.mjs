// Prints the SQL that fills public.learn_refs (the allow-list award_xp checks lesson / quiz / glossary refs against).
// Re-run whenever lessons or glossary terms are added, renamed or removed, and ship the output as a new migration:
//   node scripts/gen-learn-refs.mjs > supabase/migrations/00NN_learn_refs.sql
// Refs match what the client sends (lib/api-learn.ts markDone): the bare lesson slug for `lesson` and
// `lesson_quiz` (only lessons that have a quiz), the bare term slug for `glossary`.
import { createRequire } from "node:module";
import { mkdtempSync, readFileSync, writeFileSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ts = require("typescript");
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "lib/content");
const out = mkdtempSync(join(tmpdir(), "zl-refs-"));
for (const f of readdirSync(srcDir).filter((f) => f.endsWith(".ts"))) {
  const js = ts.transpileModule(readFileSync(join(srcDir, f), "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  }).outputText;
  writeFileSync(join(out, f.replace(/\.ts$/, ".js")), js);
}
const { GLOSSARY } = require(join(out, "glossary.js"));
const { TRACKS } = require(join(out, "lessons.js"));

const kebab = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const rows = [];
for (const t of TRACKS)
  for (const l of t.lessons) {
    rows.push(["lesson", l.slug]);
    if (Array.isArray(l.quiz) && l.quiz.length > 0) rows.push(["lesson_quiz", l.slug]);
  }
for (const g of GLOSSARY) rows.push(["glossary", g.slug]);

const seen = new Set();
for (const [k, s] of rows) {
  if (!kebab.test(s)) throw new Error(`not a kebab-case slug: ${k}/${s}`);
  if (seen.has(`${k}/${s}`)) throw new Error(`duplicate ref: ${k}/${s}`);
  seen.add(`${k}/${s}`);
}

const lines = rows.map(([k, s]) => `  ('${k}', '${s}')`);
process.stdout.write(
  [
    `-- BEGIN learn_refs — generated by scripts/gen-learn-refs.mjs (${rows.length} refs). Do not edit by hand.`,
    "delete from public.learn_refs;",
    "insert into public.learn_refs (kind, slug) values",
    lines.join(",\n") + ";",
    "-- END learn_refs",
    "",
  ].join("\n"),
);
