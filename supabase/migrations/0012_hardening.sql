-- Called when the player presses start. Returns { run_id, started_at (ms) }.
create or replace function public.start_game_run(p_game text, p_level int)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare me profiles; tok game_run_tokens;
begin
  if auth.uid() is null then raise exception 'auth_required' using errcode = '28000'; end if;
  select * into me from profiles where id = auth.uid();
  if not found then raise exception 'profile_incomplete'; end if;
  if me.banned then raise exception 'banned' using errcode = '42501'; end if;
  if _game_level_limits(p_game, p_level) is null then raise exception 'unknown_level'; end if;
  perform pg_advisory_xact_lock(hashtext('zq_game_run'), hashtext(me.id::text));
  delete from game_run_tokens where user_id = me.id and started_at < now() - interval '1 day';
  if (select count(*) from game_run_tokens where user_id = me.id and started_at >= _utc_day_start()) >= 4 * _game_daily_runs() then
    raise exception 'too_many_requests';
  end if;
  insert into game_run_tokens (user_id, game, level) values (me.id, p_game, p_level) returning * into tok;
  return jsonb_build_object('run_id', tok.id, 'started_at', _now_ms(tok.started_at));
end $$;

