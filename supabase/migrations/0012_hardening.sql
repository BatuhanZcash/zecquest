end $$;

-- Client-facing. Dönüş: { awarded, xp, level, level_floor, next_level_at }
create or replace function public.award_xp(p_source text, p_ref text) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_uid uuid := auth.uid();
  v_ref text := trim(p_ref);
  v_amt int;
  v_today int;
  v_xp int;
  me profiles;
begin
  if v_uid is null then raise exception 'auth_required' using errcode = '28000'; end if;
  if not public._xp_client_source(p_source) then raise exception 'invalid_source' using errcode = '22023'; end if;
  v_amt := public._xp_amount(p_source);
  if v_amt is null then raise exception 'invalid_source' using errcode = '22023'; end if;
  if v_ref is null or length(v_ref) = 0 or length(v_ref) > 120 then raise exception 'invalid_ref' using errcode = '22023'; end if;

  if p_source = 'news_read' then
    -- a published digest of the last 3 days (compared as text: no cast error on junk input)
    if not exists (select 1 from news_digests d
                    where d.date::text = v_ref and d.status = 'published'
                      and d.date >= (now() at time zone 'utc')::date - 3) then
      raise exception 'invalid_ref' using errcode = '22023';
    end if;
  elsif not exists (select 1 from learn_refs where kind = p_source and slug = v_ref) then
    raise exception 'invalid_ref' using errcode = '22023';
  end if;

  -- row lock: serializes this user's awards so the daily cap can't be raced
  select * into me from profiles where id = v_uid for update;
  if not found then raise exception 'profile_incomplete'; end if;
  if me.banned then raise exception 'banned' using errcode = '42501'; end if;

  if exists (select 1 from xp_events where user_id = v_uid and source = p_source and ref = v_ref) then
    return public._xp_progress(me.xp) || jsonb_build_object('awarded', 0);
  end if;

  select coalesce(sum(amount), 0) into v_today from xp_events
   where user_id = v_uid and created_at >= public._utc_day_start() and public._xp_client_source(source);
  if v_today + v_amt > public._xp_daily_cap() then
    raise exception 'xp_daily_limit' using errcode = 'P0001';
  end if;

  insert into xp_events (user_id, source, ref, amount) values (v_uid, p_source, v_ref, v_amt);
  update profiles set xp = xp + v_amt where id = v_uid returning xp into v_xp;
  return public._xp_progress(v_xp) || jsonb_build_object('awarded', v_amt);
end $$;

-- XP leaderboard: no guests, no banned accounts
