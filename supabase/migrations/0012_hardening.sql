create or replace function public._arena_before_insert() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if new.p2 is not null and exists (select 1 from profiles where id in (new.p1, new.p2) and is_guest) then
    new.rated := false;
  end if;
  return new;
end $$;
